int
sys_fork(void)
{
  return fork();
}

int
sys_exit(void)
{
  exit();
  return 0;  // not reached
}

int
sys_wait(void)
{
  return wait();
}

int
sys_kill(void)
{
  int pid;

  if(argint(0, &pid) < 0)
    return -1;
  return kill(pid);
}

int
sys_getpid(void)
{
  return proc->pid;
}

addr_t
sys_sbrk(void)
{
  addr_t addr;
  addr_t n;

  argaddr(0, &n);
  addr = proc->sz;
  if(growproc(n) < 0)
    return -1;
  return addr;
}

int
sys_sleep(void)
{
  int n;
  uint ticks0;

  if(argint(0, &n) < 0)
    return -1;
  acquire(&tickslock);
  ticks0 = ticks;
  while(ticks - ticks0 < n){
    if(proc->killed){
      release(&tickslock);
      return -1;
    }
    sleep(&ticks, &tickslock);
  }
  release(&tickslock);
  return 0;
}

// return how many clock tick interrupts have occurred
// since start.
int
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}

addr_t sys_mouseread(void){
  struct mouse_event *ev;
  if (argptr(0, (char**)&ev, sizeof(*ev)) < 0)
    return -1;
  return mouseread(ev);
}

addr_t sys_clone(void) {
  void *stack, *fn, *arg;
  int size;
  if(argaddr(0, (addr_t*)&stack) < 0) return -1;
  if(argint(1, &size) < 0) return -1;
  if(argaddr(2, (addr_t*)&fn) < 0) return -1;
  if(argaddr(3, (addr_t*)&arg) < 0) return -1;
  return clone(stack, size, fn, arg);
}